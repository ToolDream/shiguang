#!/usr/bin/env python3
"""Convert custom Shiguang toolbar SVGs to Win32 PolyDraw points."""
import argparse
import math
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/toolbar_icons"
OUTPUT = ROOT / "src/toolbar_glyph_data.h"
ICONS = ("rect", "circle", "triangle", "diamond", "arrow", "pen",
         "text", "undo", "redo", "save", "check", "caret")
GRID = 64


def arc(x, y, ex, ey, radius, sweep):
    """Convert small, unrotated circular arcs used by these SVGs."""
    dx, dy = (ex - x) / 2, (ey - y) / 2
    half = math.hypot(dx, dy)
    assert half > 0 and radius > 0
    radius = max(radius, half)  # SVG expands an arc too small to reach its endpoint.
    h = math.sqrt(radius**2 - half**2) / half * (1 if sweep else -1)
    cx, cy = x + dx - h * dy, y + dy + h * dx
    angle = math.atan2(y - cy, x - cx)
    turn = 2 * math.asin(min(1, half / radius)) * (1 if sweep else -1)
    segments = math.ceil(abs(turn) / (math.pi / 2))
    step = turn / segments
    k = 4 / 3 * math.tan(step / 4) * radius
    for i in range(segments):
        end = angle + step
        nx, ny = (ex, ey) if i == segments - 1 else (cx + radius * math.cos(end),
                                                     cy + radius * math.sin(end))
        yield (x - k * math.sin(angle), y + k * math.cos(angle))
        yield (nx + k * math.sin(end), ny - k * math.cos(end))
        yield (nx, ny)
        x, y, angle = nx, ny, end


def points(path):
    tokens = re.findall(r"[A-Za-z]|[-+]?(?:\d+(?:\.\d*)?|\.\d+)", path)
    assert "".join(tokens) == re.sub(r"[\s,]", "", path), path
    out = []
    i = 0
    x = y = 0.0
    start = (0.0, 0.0)
    cmd = None
    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]
            i += 1
        kind = cmd.upper()
        if kind == "Z":
            assert out and out[-1][2] in ("PT_LINETO", "PT_BEZIERTO")
            u, v, op = out[-1]
            out[-1] = (u, v, op + " | PT_CLOSEFIGURE")
            x, y = start
            cmd = None
            continue
        n = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "A": 7}[kind]
        args = list(map(float, tokens[i:i + n]))
        assert len(args) == n
        i += n
        rel = cmd.islower()
        if kind == "H":
            xy = [(args[0] + (x if rel else 0.0), y)]
        elif kind == "V":
            xy = [(x, args[0] + (y if rel else 0.0))]
        else:
            coords = args[-2:] if kind == "A" else args
            xy = [(u + (x if rel else 0.0), v + (y if rel else 0.0))
                  for u, v in zip(coords[::2], coords[1::2])]
        if kind == "A":
            rx, ry, rotation, large, sweep, _, _ = args
            assert rx == ry and rotation == large == 0 and sweep in (0, 1)
            xy = list(arc(x, y, *xy[0], rx, sweep))
        x, y = xy[-1]
        op = {"M": "PT_MOVETO", "C": "PT_BEZIERTO", "A": "PT_BEZIERTO"}.get(kind, "PT_LINETO")
        out.extend((u, v, op) for u, v in xy)
        if kind == "M":
            start = (x, y)
            cmd = "l" if rel else "L"
    return out


def paths(name):
    root = ET.parse(SOURCE / (name + ".svg")).getroot()
    assert all(root.get(k) == v for k, v in {
        "viewBox": "0 0 24 24", "fill": "none", "stroke": "currentColor",
        "stroke-linecap": "round", "stroke-linejoin": "round",
    }.items()), name
    stroke_paths = []
    fill_paths = []
    for el in root:
        kind = el.tag.removeprefix("{http://www.w3.org/2000/svg}")
        a = el.attrib
        if kind == "path":
            d = a["d"]
        elif kind == "polyline":
            d = "M" + a["points"]
        elif kind == "line":
            d = f'M{a["x1"]} {a["y1"]}L{a["x2"]} {a["y2"]}'
        elif kind == "circle":
            x, y, r = (float(a[k]) for k in ("cx", "cy", "r"))
            d = f"M{x-r} {y}a{r} {r} 0 0 1 {2*r} 0a{r} {r} 0 0 1 {-2*r} 0Z"
        elif kind == "rect":
            x, y, w, h, r = (float(a[k]) for k in ("x", "y", "width", "height", "rx"))
            assert float(a.get("ry", r)) == r
            turn = f"a{r} {r} 0 0 1"
            d = (f"M{x+r} {y}H{x+w-r}{turn} {r} {r}V{y+h-r}{turn} {-r} {r}"
                 f"H{x+r}{turn} {-r} {-r}V{y+r}{turn} {r} {-r}Z")
        else:
            raise ValueError(kind)
        if a.get("fill") == "currentColor":
            fill_paths.append(d)
        if a.get("stroke") != "none":
            stroke_paths.append(d)
    return stroke_paths, fill_paths


def emit_array(lines, symbol, data):
    lines.append(f"static const GlyphPoint {symbol}[] = {{")
    for x, y, op in data:
        lines.append(f"    {{{round(x * GRID)}, {round(y * GRID)}, {op}}},")
    lines.append("};")


def generate():
    assert {f.stem for f in SOURCE.glob("*.svg")} == set(ICONS)
    lines = ["// Generated by scripts/generate_toolbar_glyphs.py. See src/toolbar_icons/.",
             f"enum {{ GLYPH_GRID = {GRID} }};"]
    largest = 0
    for name in ICONS:
        stroke_paths, fill_paths = paths(name)
        stroke_data = [point for path in stroke_paths for point in points(path)]
        fill_data = [point for path in fill_paths for point in points(path)]
        assert stroke_data or fill_data, name
        for data in (stroke_data, fill_data):
            largest = max(largest, len(data))
            assert all(0 <= v <= 24 for x, y, _ in data for v in (x, y)), name
        sym = name.replace("-", "_")
        if stroke_data:
            emit_array(lines, f"glyph_{sym}", stroke_data)
        if fill_data:
            emit_array(lines, f"glyph_{sym}_fill", fill_data)
    lines.append(f"enum {{ GLYPH_MAX_POINTS = {largest} }};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="ascii") != output:
            parser.exit(1, "Toolbar glyph data is stale; run scripts/generate_toolbar_glyphs.py\n")
    else:
        OUTPUT.write_text(output, encoding="ascii")
